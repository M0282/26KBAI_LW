def _make(path: Path, lines: list[tuple[str, int]]) -> None:
    doc = fitz.open()
    page = doc.new_page()
    page.insert_font(fontname="malgun", fontfile=FONT_PATH)
    y = 60
    for text, size in lines:
        if text:
            page.insert_text((56, y), text, fontname="malgun", fontsize=size)
        y += (size + 9) if size else 11
    # 한글 폰트 전체를 임베드하면 파일 하나가 13MB를 넘는다. 쓰는 글자만 남긴다.
    doc.subset_fonts()
    doc.set_metadata({})
    doc.save(str(path), garbage=4, deflate=True)
    doc.close()


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, lines in DOCS.items():
        _make(OUT / name, lines)
        print(f"  생성: {OUT / name}  ({(OUT / name).stat().st_size:,}B)")
    print(f"\nKB 서식 데모 {len(DOCS)}종 생성 완료 → {OUT}")
    print("이어서(키 보유자 1회): py -3 -m scripts.build_demo_results \"data/samples/kb_demo/*.pdf\"")
    return 0


